def get_partial(name: str, animated: bool = False) -> Optional[discord.PartialEmoji]:
    """Returns a discord.PartialEmoji for the given emoji name."""
    emoji_id = id_for(name)
    if not emoji_id:
        return None
    
    # Find the actual name case from EMOJI_IDS
    actual_name = name
    for n in EMOJI_IDS.keys():
        if n.lower() == name.lower():
            actual_name = n
            break
            
    # Clean ID if it's too short (potential copy-paste error)
    if len(str(emoji_id)) < 15:
        return None
        
    return discord.PartialEmoji(name=actual_name, id=emoji_id, animated=animated)

def get_animated_partial(name: str) -> Optional[discord.PartialEmoji]:
    """Returns a discord.PartialEmoji for an animated emoji name."""
    for n, emoji_id in ANIMATED_EMOJI_IDS.items():
        if n.lower() == name.lower():
            return discord.PartialEmoji(name=n, id=emoji_id, animated=True)
    return None
